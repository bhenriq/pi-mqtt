#!/bin/sh
# Builds the password file and the role ACL from PI_MQTT_USERS, then starts mosquitto.
#
# Each entry is one of:
#
#   name:password                  legacy: one user, read/write everything
#   name:password:orchestrator:room  may dispatch, kick, and read results
#   name:password:worker:room        may be dispatched to, and nothing else
#
# Example:
#
#   PI_MQTT_USERS="tribe:$ORCH, pru:$WORKERS"
#
# Passwords cannot contain ':' or ','. Role-scoped users get an ACL for that room only;
# a legacy entry keeps the old read/write-everything grant and is reported at boot, so
# an existing single-credential deployment keeps working.
#
# There is no per-device worker form. Worker ids are "<name>_<pi session>", and MQTT
# filters cannot match a prefix inside a topic level — "workers/pru_+/ctl" is not a
# valid filter — so one worker credential cannot be confined to one machine without a
# topic layout where the name is its own level. See deploy/README.md.
#
# Railway env vars are visible to the service, not to clients. Rotate by editing the
# variable and redeploying; sessions reconnect on their own.

set -eu

: "${PI_MQTT_USERS:?set PI_MQTT_USERS to a comma-separated user:password list}"

# Defaults match the image layout; the overrides exist so this script can be
# exercised on a laptop without Docker.
CONFIG_DIR=${MOSQUITTO_CONFIG_DIR:-/mosquitto/config}
DATA_DIR=${MOSQUITTO_DATA_DIR:-/mosquitto/data}
MOSQUITTO_BIN=${MOSQUITTO_BIN:-mosquitto}
PASSWD_FILE="$CONFIG_DIR/passwd"
ACL_FILE="$CONFIG_DIR/acl"

mkdir -p "$CONFIG_DIR" "$DATA_DIR"

valid_id() {
	case "$1" in
	"" | *[!A-Za-z0-9_-]*) return 1 ;;
	[!A-Za-z0-9]*) return 1 ;;
	esac
	[ ${#1} -le 64 ]
}

# Rewrite from scratch so removing an entry in PI_MQTT_USERS revokes access.
# `mosquitto_passwd -c` refuses an existing file, so delete rather than truncate.
rm -f "$PASSWD_FILE"
rm -f "$ACL_FILE"

cat >"$ACL_FILE" <<'HEADER'
# Generated by pi-mqtt-entrypoint from PI_MQTT_USERS. Do not edit inside the image.
#
# Roles are capabilities, not claims: only an orchestrator credential may write a
# worker's control topic (dispatch), the room control topic (kick), or read results.
# A worker credential can be dispatched to and report, and nothing more.

HEADER

count=0
legacy=0
old_ifs=$IFS
IFS=','
set -f
for entry in $PI_MQTT_USERS; do
	IFS=$old_ifs
	# Trim blanks around each entry: "a:x, b:y" is the documented form, and a stray
	# space would otherwise become part of the username.
	entry=${entry#"${entry%%[![:space:]]*}"}
	entry=${entry%"${entry##*[![:space:]]}"}
	[ -n "$entry" ] || continue
	case "$entry" in
	*:*) ;;
	*) echo "ignoring malformed PI_MQTT_USERS entry (want name:password)" >&2; continue ;;
	esac

	user=${entry%%:*}
	rest=${entry#*:}
	password=${rest%%:*}

	# Fields 3.. of this entry. `rest` is "password[:role:room]", so stripping one
	# segment when there was none means a two-field, role-less entry.
	fields=${rest#*:}
	role=
	room=
	if [ "$fields" != "$rest" ]; then
		role=${fields%%:*}
		case "$fields" in
		*:*)
			after_role=${fields#*:}
			room=${after_role%%:*}
			case "$after_role" in
			*:*)
				echo "ignoring user $user: too many fields (want name:password[:role:room]); per-device worker ACLs are not expressible with this topic layout" >&2
				continue
				;;
			esac
			;;
		esac
	fi

	if [ -z "$user" ] || [ -z "$password" ]; then
		echo "ignoring malformed PI_MQTT_USERS entry (empty name or password)" >&2
		continue
	fi

	# Validate before touching the password file: a credential with no ACL entries
	# silently cannot do anything, which is a confusing thing to debug.
	if [ -n "$role" ]; then
		case "$role" in
		orchestrator | orch) role=orchestrator ;;
		worker) ;;
		*)
			echo "ignoring user $user: role must be orchestrator or worker, got '$role'" >&2
			continue
			;;
		esac
		if ! valid_id "$room"; then
			echo "ignoring user $user: room must be a letters/digits/_/- identifier, got '${room%%,*}'" >&2
			continue
		fi
	fi

	if [ "$count" = 0 ]; then
		mosquitto_passwd -b -c "$PASSWD_FILE" "$user" "$password"
	else
		mosquitto_passwd -b "$PASSWD_FILE" "$user" "$password"
	fi
	count=$((count + 1))

	if [ -z "$role" ]; then
		legacy=$((legacy + 1))
		cat >>"$ACL_FILE" <<LEGACY

# $user: legacy entry, NOT role-scoped. Any member with this credential can dispatch,
# kick, and read every result. Give it a role and a room to confine it.
user $user
topic readwrite pi/v1/#
LEGACY
		echo "configured user: $user (legacy: full access)" >&2
		continue
	fi

	case "$role" in
	orchestrator)
		cat >>"$ACL_FILE" <<ORCH

# $user: orchestrator in room "$room" — dispatches, kicks, reads results.
user $user
topic write pi/v1/$room/workers/+/ctl
topic write pi/v1/$room/workers/+/pair
topic read pi/v1/$room/workers/+/presence
topic read pi/v1/$room/workers/+/ack
topic readwrite pi/v1/$room/control
topic read pi/v1/$room/results/+
topic readwrite pi/v1/$room/orchestrators/+/presence
ORCH
		;;
	worker)
		cat >>"$ACL_FILE" <<WORKER

# $user: worker in room "$room" — may be dispatched to; cannot dispatch, kick, or read
# results. The credential is shared by the room's workers, so the broker cannot tell
# them apart: any of them can read every worker's control topic, and overwrite another
# worker's presence entry.
user $user
topic read pi/v1/$room/workers/+/ctl
topic read pi/v1/$room/workers/+/pair
topic readwrite pi/v1/$room/workers/+/presence
topic write pi/v1/$room/workers/+/ack
topic write pi/v1/$room/results/+
topic read pi/v1/$room/control
WORKER
		;;
	esac
	echo "configured user: $user ($role, room $room)" >&2
done
IFS=$old_ifs
set +f

if [ "$count" = 0 ]; then
	echo "PI_MQTT_USERS produced no users; refusing to start an open broker" >&2
	exit 1
fi
if [ "$legacy" -gt 0 ] && [ "$count" -eq "$legacy" ]; then
	echo "warning: every user is a legacy entry, so roles are not enforced by the broker" >&2
fi

# Only meaningful in the image, where this runs as root before dropping privileges.
if [ "$(id -u)" = 0 ]; then
	chown -R mosquitto:mosquitto "$CONFIG_DIR" "$DATA_DIR" 2>/dev/null || true
fi
chmod 600 "$PASSWD_FILE"
chmod 640 "$ACL_FILE"

exec "$MOSQUITTO_BIN" -c "$CONFIG_DIR/mosquitto.conf"
